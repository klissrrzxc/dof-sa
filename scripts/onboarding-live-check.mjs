// Explicit manual integration check. Creates one labelled temporary applicant; never prints credentials.
import {chromium} from '@playwright/test';
import {randomBytes} from 'node:crypto';
const browser=await chromium.launch();
const page=await browser.newPage();
const password=randomBytes(24).toString('base64url');
await page.goto('http://127.0.0.1:3000/register');
await page.getByLabel('Static ID',{exact:true}).fill('999999999991');
await page.getByLabel('Имя и фамилия').fill('TEST ACCESS TEMP');
await page.getByLabel('Игровой номер телефона').fill('TEST-000');
await page.getByLabel('Организация',{exact:true}).fill('TEST ACCESS TEMP ORGANIZATION');
await page.getByLabel('Приказ / документ').fill('TEST ORDER TEMP');
await page.getByLabel('Ваш пароль',{exact:true}).fill(password);
await page.getByLabel('Повторите пароль').fill(password);
await page.getByRole('checkbox').check();
await page.getByRole('button',{name:'Отправить заявку на доступ'}).click();
await page.getByRole('status').waitFor({timeout:30000});
await page.goto('http://127.0.0.1:3000/login');
await page.getByLabel('Static ID / email').fill('999999999991');
await page.getByLabel('Пароль',{exact:true}).fill(password);
await page.getByRole('button',{name:'Войти в систему'}).click();
await page.waitForURL('**/auth/pending');
console.log('PASS pending applicant blocked. Awaiting temporary admin approval.');
await new Promise(resolve=>process.stdin.once('data',resolve));
await page.reload();await page.waitForURL('**/app');
await page.goto('http://127.0.0.1:3000/app/cases/new');
if(!await page.locator('input[value="999999999991"]').count())throw new Error('Static ID not prefilled');
await page.goto('http://127.0.0.1:3000/app/treasury');
if(!(await page.textContent('body')).includes('403'))throw new Error('Treasury access must be denied');
console.log('PASS approved applicant can open case form without MFA and cannot access treasury.');
await browser.close();
